"""Skeleton definitions for Cardboard Colin.

Every designed glyph is a set of centre-line strokes drawn in a normalised box:
x in [0, 1] spans the glyph's centre-line width, y in [0, 1] spans baseline..cap
(or baseline..small-cap height for lowercase). Values outside 0..1 are allowed
(descenders, overshoot). Each stroke is (points, closed). Strokes are buffered to
the marker width, then roughened with the same noise as Colin's real letters.

Glyph widths are outer widths in pixels at the 480 px cap-height drawing scale.
"""

def S(*pts, closed=False):
    return (list(pts), closed)

